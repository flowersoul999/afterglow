/**
 * 理财技能图数据 —— 修行录第三图
 *
 * 定位：全站三张修行录里**唯一有复利效应**的一张。
 * 前两张（音乐 / 英语）是「不学不会立刻出事，但越晚学代价越大」；
 * 理财是「学会了之后每一年的收益都叠加」，而且它是唯一一张
 * **清单可以精确到数字**的图 —— 储蓄率、应急月数、定投次数，全是硬指标，
 * 勾完能对账，不像别的图只能凭感觉。
 *
 * 走修行录（无门禁、不加修为、不发传书、不领话本签）：
 *   · 理财和 cs / fe / be / ag 没有先后关系，硬塞进修仙境界链会出荒谬门禁
 *   · 也不该因为「练理财能结丹」而扭曲修为体系 —— 钱不是修为
 *
 * 和英语图一样，这张图有**自己的等级体系**（`FN_LEVELS`）：
 * 技术图那套「做过可运行的东西 / 写过被广泛使用的库」放到理财上全是空话。
 * 理财的终点是「财务自由有路径」，不是造轮子。
 *
 * 方向划分按**真实的能力增长顺序**，不是按产品分类：
 *   记账（看清现状）→ 预算（管住流出）→ 应急储备（活过意外）
 * → 消费决策（把判断力变成习惯）→ 债务（先清高息）→ 保障（转移不能承受的风险）
 * → 投资（让钱生钱）→ 长期规划（养老与传承）
 * 顺序是有道理的：不记账就做不出预算，没有预算就没有储备，
 * 带着高息债务去投资是负收益，缺保障就等于把一次大病变成负债。
 *
 * 图标见 src/data/financeIcons.ts（自动生成），key 与 id 一致。
 * 学习清单见 src/data/financeChecks.ts。
 */
